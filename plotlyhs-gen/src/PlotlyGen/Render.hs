{-# LANGUAGE OverloadedStrings #-}

-- | Renders the generated Haskell modules.
module PlotlyGen.Render
  ( Module (..),
    renderModules,
    haddock,
  )
where

import Data.Aeson (Value (..), encode)
import Data.ByteString.Lazy qualified as BL
import Data.List (sortOn)
import Data.Map.Strict (Map)
import Data.Map.Strict qualified as Map
import Data.Maybe (catMaybes)
import Data.Scientific (floatingOrInteger)
import Data.Text (Text)
import Data.Text qualified as T
import Data.Text.Encoding qualified as TE
import PlotlyGen.Naming
import PlotlyGen.Schema

data Module = Module
  { moduleName :: Text,
    moduleBody :: Text
  }

-- | Leaf attributes a layout object needs before it gets a module of its own.
splitThreshold :: Int
splitThreshold = 30

renderModules :: Text -> Schema -> [EnumDef] -> [Module]
renderModules version schema enums =
  [versionModule version, traceTypeModule version (schemaTraces schema), enumsModule version enums, tracesModule version (schemaTraces schema)]
    <> map (traceModule version names) (schemaTraces schema)
    <> layoutModules version names (schemaLayout schema)
    <> [ instancesModule version names "Graphics.Plotly.Config" "The plot's configuration: @config@ in @Plotly.newPlot@." (objectsIn' (schemaConfig schema)),
         instancesModule version names "Graphics.Plotly.Frame" "Animation frames." (objectsIn' (schemaFrame schema)),
         instancesModule version names "Graphics.Plotly.Animation" "Options for @Plotly.animate@." (objectsIn' (schemaAnimation schema))
       ]
  where
    names = Map.fromList [(enumKey e, enumName e) | e <- enums]

header :: Text -> [Text] -> Text
header version pragmas =
  T.unlines $
    [ "-- This module is generated by plotlyhs-gen from the plot-schema.json of",
      "-- plotly.js " <> version <> ". Do not edit it; run plotlyhs-gen instead."
    ]
      <> pragmas

instancePragmas :: [Text]
instancePragmas =
  [ "{-# LANGUAGE DataKinds #-}",
    "{-# LANGUAGE OverloadedStrings #-}",
    "{-# LANGUAGE UndecidableInstances #-}",
    "{-# OPTIONS_GHC -Wno-orphans -Wno-unused-imports #-}"
  ]

instanceImports :: [Text]
instanceImports =
  [ "import Data.Aeson (Value)",
    "import Data.Text (Text)",
    "import Graphics.Plotly.Core",
    "import Graphics.Plotly.Enums",
    "import Graphics.Plotly.TraceType",
    "import Graphics.Plotly.Types",
    "import Optics.Core (A_Lens, LabelOptic (..))"
  ]

-- * Version

versionModule :: Text -> Module
versionModule version =
  Module "Graphics.Plotly.Version" $
    T.unlines
      [ header version ["{-# LANGUAGE OverloadedStrings #-}"],
        "-- | The version of plotly.js the library is generated from.",
        "module Graphics.Plotly.Version (plotlyJsVersion) where",
        "",
        "import Data.Text (Text)",
        "",
        "-- | The version of plotly.js whose schema the library is generated from,",
        "-- and whose bundle is vendored.",
        "plotlyJsVersion :: Text",
        "plotlyJsVersion = " <> str version
      ]

-- * Trace types

traceTypeModule :: Text -> [TraceDef] -> Module
traceTypeModule version traces =
  Module "Graphics.Plotly.TraceType" $
    T.unlines $
      [ header version ["{-# LANGUAGE DataKinds #-}", "{-# LANGUAGE OverloadedStrings #-}"],
        "-- | The trace types of plotly.js.",
        "module Graphics.Plotly.TraceType",
        "  ( TraceType (..),",
        "    KnownTraceType (..),",
        "    traceTypeName,",
        "    traceTypeFromName,",
        "  )",
        "where",
        "",
        "import Data.Text (Text)",
        "",
        "-- | A trace type. Promoted, it indexes 'Graphics.Plotly.Core.Trace'.",
        "data TraceType"
      ]
        <> zipWith (\i t -> "  " <> (if i == (0 :: Int) then "= " else "| ") <> traceCtor (traceName t)) [0 ..] traces
        <> [ "  deriving stock (Eq, Ord, Show, Read, Enum, Bounded)",
             "",
             "-- | The name plotly.js uses for a trace type, its @type@ attribute.",
             "traceTypeName :: TraceType -> Text",
             "traceTypeName = \\case"
           ]
        <> ["  " <> traceCtor (traceName t) <> " -> " <> str (traceName t) | t <- traces]
        <> [ "",
             "-- | The trace type plotly.js calls by the given name.",
             "traceTypeFromName :: Text -> Maybe TraceType",
             "traceTypeFromName = \\case"
           ]
        <> ["  " <> str (traceName t) <> " -> Just " <> traceCtor (traceName t) | t <- traces]
        <> [ "  _ -> Nothing",
             "",
             "-- | Trace types known at compile time.",
             "class KnownTraceType (t :: TraceType) where",
             "  -- | The trace type, as a value.",
             "  traceTypeOf :: proxy t -> TraceType"
           ]
        <> concat
          [ ["", "instance KnownTraceType '" <> c <> " where", "  traceTypeOf _ = " <> c]
          | t <- traces,
            let c = traceCtor (traceName t)
          ]

-- * Enumerations

enumsModule :: Text -> [EnumDef] -> Module
enumsModule version enums =
  Module "Graphics.Plotly.Enums" $
    T.unlines $
      [ header version ["{-# LANGUAGE OverloadedStrings #-}", "{-# OPTIONS_GHC -Wno-unused-imports #-}"],
        "-- | The enumerations of plotly.js's attributes. One type stands for each",
        "-- distinct set of values, wherever it is used. Constructors are prefixed",
        "-- with their type's name.",
        "module Graphics.Plotly.Enums",
        "  ( " <> T.intercalate ",\n    " [enumName e <> " (..)" | e <- enums] <> ",",
        "  )",
        "where",
        "",
        "import Data.Aeson qualified as A",
        "import Graphics.Plotly.Types (SubplotId (..), enumMismatch, parseEnum)",
        "import Prelude (Bool (..), Bounded (..), Double, Enum, Eq, Int, Ord, Show, pure, ($), (<$>))"
      ]
        <> concatMap renderEnum enums

renderEnum :: EnumDef -> [Text]
renderEnum e =
  [ "",
    "-- | " <> (if ekFlags (enumKey e) then "Flags of " else "Values of ") <> users <> "."
  ]
    <> ["-- Combine them with 'Graphics.Plotly.Types.Flags'." | ekFlags (enumKey e)]
    <> ["data " <> name]
    <> zipWith (\i c -> "  " <> (if i == (0 :: Int) then "= " else "| ") <> ctorDecl c) [0 ..] (enumCtors e)
    <> [ "  deriving stock (Eq, Ord, Show" <> (if hasPayload then "" else ", Enum, Bounded") <> ")",
         "",
         "instance A.ToJSON " <> name <> " where",
         "  toJSON = \\case"
       ]
    <> ["    " <> toCase c | c <- enumCtors e]
    <> [ "",
         "instance A.FromJSON " <> name <> " where"
       ]
    <> case [c | c@(CPayload _ _) <- enumCtors e] of
      [] -> ["  parseJSON = parseEnum [minBound .. maxBound] (enumMismatch " <> str name <> ")"]
      payloads ->
        [ "  parseJSON = parseEnum [" <> T.intercalate ", " [n | CConst n _ <- enumCtors e] <> "] $ \\case"
        ]
          <> ["    " <> fromCase c | c <- payloads]
          <> ["    v -> enumMismatch " <> str name <> " v"]
  where
    name = enumName e
    hasPayload = not (null [() | CPayload _ _ <- enumCtors e])
    paths = enumUsers e
    users =
      T.intercalate ", " (map (\p -> "@" <> escape p <> "@") (take 4 paths))
        <> (if length paths > 4 then " and " <> T.pack (show (length paths - 4)) <> " more" else "")
    ctorDecl (CConst n _) = n
    ctorDecl (CPayload n t) = n <> " " <> t
    toCase (CConst n v) = n <> " -> " <> jsonOf v
    toCase (CPayload n _) = n <> " x -> A.toJSON x"
    fromCase (CPayload n "SubplotId") = "A.String x -> pure (" <> n <> " (SubplotId x))"
    fromCase (CPayload n _) = "v@(A.Number _) -> " <> n <> " <$> A.parseJSON v"
    fromCase (CConst n _) = n
    jsonOf = \case
      VBool b -> "A.Bool " <> T.pack (show b)
      VNum n -> case floatingOrInteger n :: Either Double Integer of
        Right i -> "A.Number (" <> T.pack (show i) <> ")"
        Left d -> "A.Number (" <> T.pack (show d) <> ")"
      VStr s -> "A.String " <> str s

-- * Traces

tracesModule :: Text -> [TraceDef] -> Module
tracesModule version traces =
  Module "Graphics.Plotly.Traces" $
    T.unlines $
      [ header version [],
        "-- | Every trace type's constructor.",
        "module Graphics.Plotly.Traces",
        "  ( " <> T.intercalate ",\n    " ["module " <> traceModuleName t | t <- traces] <> ",",
        "  )",
        "where",
        ""
      ]
        <> ["import " <> traceModuleName t | t <- traces]

traceModuleName :: TraceDef -> Text
traceModuleName t = "Graphics.Plotly.Trace." <> pascal (traceName t)

traceModule :: Text -> Map EnumKey Text -> TraceDef -> Module
traceModule version names t =
  Module (traceModuleName t) $
    T.unlines $
      [ header version instancePragmas,
        "-- | The @" <> traceName t <> "@ trace type." <> maybe "" (\d -> "\n--\n-- " <> haddock d) (traceDoc t),
        "module " <> traceModuleName t <> " (" <> traceName t <> ") where",
        ""
      ]
        <> instanceImports
        <> [ "",
             "-- | A new @" <> traceName t <> "@ trace, with no attributes set.",
             traceName t <> " :: Trace '" <> traceCtor (traceName t),
             traceName t <> " = newTrace"
           ]
        <> concatMap (objInstances names) (objectsIn' (traceAttrs t))

-- * Layout, config, frames, animation

layoutModules :: Text -> Map EnumKey Text -> ObjDef -> [Module]
layoutModules version names layout =
  Module "Graphics.Plotly.Layout" rootBody : [sub k o | (k, o) <- split]
  where
    big o = length [() | o' <- objectsIn' o, CLeaf _ _ <- objChildren o'] >= splitThreshold
    split = [(k, o) | c <- objChildren layout, Just (k, o) <- [childObj c], big o]
    splitPaths = map (objPath . snd) split
    inRoot = [o | o <- objectsIn' layout, not (any (`isPrefixOfPath` objPath o) splitPaths)]
    subName k = "Graphics.Plotly.Layout." <> pascal k
    subplots = [(k, o) | CObject k _ True o <- objChildren layout]
    rootBody =
      T.unlines $
        [ header version instancePragmas,
          "-- | The layout: everything about a figure other than its traces.",
          "module Graphics.Plotly.Layout",
          "  ( " <> T.intercalate ",\n    " [k <> "N" | (k, _) <- subplots] <> ",",
          "  )",
          "where",
          ""
        ]
          <> instanceImports
          <> ["import " <> subName k <> " ()" | (k, _) <- split]
          <> ["import Optics.Core (Lens')"]
          <> concat
            [ [ "",
                "-- | The @" <> k <> "@ subplot with the given number: 1 is @" <> k <> "@, 2 is @" <> k <> "2@, and so on.",
                k <> "N :: Int -> Lens' Layout " <> objType o,
                k <> "N n = nested (subplotKey " <> str k <> " n)"
              ]
            | (k, o) <- subplots
            ]
          <> concatMap (objInstances names) inRoot
    sub k o =
      Module (subName k) $
        T.unlines $
          [ header version instancePragmas,
            "-- | The layout's @" <> k <> "@.",
            "module " <> subName k <> " () where",
            ""
          ]
            <> instanceImports
            <> concatMap (objInstances names) (objectsIn' o)

instancesModule :: Text -> Map EnumKey Text -> Text -> Text -> [ObjDef] -> Module
instancesModule version names name doc objs =
  Module name $
    T.unlines $
      [ header version instancePragmas,
        "-- | " <> doc,
        "module " <> name <> " () where",
        ""
      ]
        <> instanceImports
        <> concatMap (objInstances names) objs

childObj :: Child -> Maybe (Text, ObjDef)
childObj (CObject k _ _ o) = Just (k, o)
childObj (CArray k _ o) = Just (k, o)
childObj _ = Nothing

isPrefixOfPath :: [Text] -> [Text] -> Bool
isPrefixOfPath p q = take (length p) q == p

objectsIn' :: ObjDef -> [ObjDef]
objectsIn' o = o : concat [objectsIn' c | Just (_, c) <- map childObj (objChildren o)]

-- * Instances

-- | The Haskell type of an object.
objType :: ObjDef -> Text
objType o = case objPath o of
  [t] | t `notElem` ["layout", "config", "frame", "animation"] -> "(Trace '" <> traceCtor t <> ")"
  _ -> "(Obj " <> str (objPathText o) <> ")"

objInstances :: Map EnumKey Text -> ObjDef -> [Text]
objInstances names o = concatMap inst (sortOn childKey (objChildren o))
  where
    s = objType o
    childKey (CLeaf k _) = k
    childKey (CObject k _ _ _) = k
    childKey (CArray k _ _) = k
    inst = \case
      CLeaf k l -> instanceFor k (leafDocs l) ("Maybe " <> typeText names True (leafType l)) "field"
      CObject k doc _ c -> instanceFor k doc (objType c) "nested"
      CArray k doc c -> instanceFor k doc ("(Maybe [Obj " <> str (objPathText c) <> "])") "field"
    instanceFor k doc a optic =
      [""]
        <> maybe [] (\d -> ["-- | " <> haddock d]) doc
        <> [ "instance (k ~ A_Lens, a ~ " <> unparen a <> ", b ~ " <> unparen a <> ") => LabelOptic " <> str k <> " k " <> s <> " " <> s <> " a b where",
             "  labelOptic = " <> optic <> " " <> str k
           ]
    unparen t = case T.stripPrefix "(" t >>= T.stripSuffix ")" of
      Just inner | balanced inner -> inner
      _ -> t
    balanced = go (0 :: Int) . T.unpack
      where
        go n [] = n == 0
        go n (c : cs)
          | c == '(' = go (n + 1) cs
          | c == ')' = n > 0 && go (n - 1) cs
          | otherwise = go n cs

leafDocs :: Leaf -> Maybe Text
leafDocs l = case catMaybes [leafDoc l, extra] of
  [] -> Nothing
  ds -> Just (T.intercalate " " ds)
  where
    extra = case catMaybes [("Default: " <>) <$> (leafDefault l >>= json), range] of
      [] -> Nothing
      ds -> Just ("(" <> T.intercalate "; " ds <> ".)")
    range = case (leafMin l >>= json, leafMax l >>= json) of
      (Just lo, Just hi) -> Just ("Range: " <> lo <> " to " <> hi)
      (Just lo, Nothing) -> Just ("Minimum: " <> lo)
      (Nothing, Just hi) -> Just ("Maximum: " <> hi)
      _ -> Nothing
    json v = case v of
      Null -> Nothing
      _ ->
        let t = TE.decodeUtf8 (BL.toStrict (encode v))
         in if T.length t > 80 then Nothing else Just ("`" <> t <> "`")

-- | Render a type, in parentheses if it is compound and 'True' asks for it.
typeText :: Map EnumKey Text -> Bool -> HsType -> Text
typeText names atomic = \case
  TDouble -> "Double"
  TInt -> "Int"
  TBool -> "Bool"
  TText -> "Text"
  TValue -> "Value"
  TColor -> "Color"
  TColorscale -> "Colorscale"
  TDataArray -> "DataArray"
  TSubplotId -> "SubplotId"
  TAngle -> "Angle"
  TEnum k _ -> names Map.! k
  TFlags k _ -> paren ("Flags " <> names Map.! k)
  TArrayOk t -> paren ("ArrayOk " <> typeText names True t)
  TTuple ts -> "(" <> T.intercalate ", " (map (typeText names False) ts) <> ")"
  TList t -> "[" <> typeText names False t <> "]"
  TNamed n -> n
  where
    paren t = if atomic then "(" <> t <> ")" else t

-- * Text

-- | A Haskell string literal.
str :: Text -> Text
str = T.pack . show

-- | Turn a schema description into Haddock markup, on one line. Backquoted
-- spans and plotly's @*value*@ quoting become code.
haddock :: Text -> Text
haddock = go . T.map (\c -> if c == '\n' then ' ' else c) . T.strip
  where
    go t = case T.break (`elem` ("`*" :: String)) t of
      (before, rest) | T.null rest -> escape before
      (before, rest) ->
        let q = T.head rest
            (inner, after) = T.break (== q) (T.tail rest)
         in if not (T.null after) && validSpan q inner
              then escape before <> "@" <> escape inner <> "@" <> go (T.tail after)
              else escape before <> escape (T.singleton q) <> go (T.tail rest)
    validSpan q inner =
      not (T.null inner) && (q == '`' || (T.strip inner == inner && not (T.any (== ' ') inner && T.length inner > 40)))

escape :: Text -> Text
escape = T.concatMap $ \c ->
  if c `elem` ("\\/'`\"@<>#*_$[]" :: String) then T.pack ['\\', c] else T.singleton c
