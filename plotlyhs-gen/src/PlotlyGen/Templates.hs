{-# LANGUAGE OverloadedStrings #-}

-- | Renders plotly.py's templates, vendored as JSON files, as
-- @Graphics.Plotly.Template.Builtin@: one binding per file, embedded and
-- checked at compile time.
module PlotlyGen.Templates
  ( renderTemplateModule,
    templateBinding,
  )
where

import Control.Monad (forM_, unless)
import Data.Aeson (Value (..))
import Data.Aeson.KeyMap qualified as KM
import Data.Char (isAsciiLower, isDigit)
import Data.List (elemIndex, sortOn)
import Data.Maybe (fromMaybe)
import Data.Text (Text)
import Data.Text qualified as T
import PlotlyGen.Naming (duplicates, pascal)
import PlotlyGen.Render (Module (..), leading, str)

-- | What each template is for, in the order plotly.py lists them. A
-- vendored template not listed here goes after them, with a plain
-- description; one listed here but not vendored is an error, so that a
-- renamed template is noticed.
templateDocs :: [(Text, Text)]
templateDocs =
  [ ("plotly", "plotly.py's default template."),
    ("plotly_white", "@plotly_white@: 'plotly' on a white background."),
    ("plotly_dark", "@plotly_dark@: 'plotly' on a dark background."),
    ("ggplot2", "@ggplot2@: in the style of R's ggplot2."),
    ("seaborn", "@seaborn@: in the style of Python's seaborn."),
    ("simple_white", "@simple_white@: white, with no grid lines."),
    ("presentation", "@presentation@: larger text and lines. Combine it with another:\n-- @plotlyWhite <> presentation@."),
    ("gridon", "@gridon@: grid lines on both axes. Combine it with another."),
    ("xgridoff", "@xgridoff@: no x grid lines. Combine it with another."),
    ("ygridoff", "@ygridoff@: no y grid lines. Combine it with another.")
  ]

-- | The module, given plotly.py's version and each template's name (its
-- file name without @.json@) and parsed JSON.
renderTemplateModule :: Text -> [(Text, Value)] -> Either String Module
renderTemplateModule version files = do
  forM_ files $ \(n, v) -> do
    unless (T.all (\c -> isAsciiLower c || isDigit c || c == '_') n && maybe False (isAsciiLower . fst) (T.uncons n)) $
      Left ("template name is not a Haskell identifier in snake case: " <> T.unpack n)
    case v of
      Object o
        | all (`elem` ["data", "layout"]) (KM.keys o) -> pure ()
      _ -> Left ("template " <> T.unpack n <> " is not an object of data and layout")
  let missing = [n | (n, _) <- templateDocs, n `notElem` map fst files]
      names = sortOn (\n -> (fromMaybe (length templateDocs) (elemIndex n (map fst templateDocs)), n)) (map fst files)
      clashes = duplicates ("templates" : map templateBinding names)
  unless (null missing) $ Left ("templates documented but not vendored: " <> show missing)
  unless (null clashes) $ Left ("template names clash: " <> show clashes)
  pure $
    Module "Graphics.Plotly.Template.Builtin" $
      T.unlines $
        [ "-- This module is generated by plotlyhs-gen from the templates of",
          "-- plotly.py " <> version <> ". Do not edit it; run plotlyhs-gen instead.",
          "{-# LANGUAGE OverloadedStrings #-}",
          "{-# LANGUAGE TemplateHaskell #-}",
          "",
          "-- | plotly.py's templates, embedded in the library. Use them through",
          "-- \"Graphics.Plotly.Template\".",
          "module Graphics.Plotly.Template.Builtin",
          "  ( templates,",
          T.intercalate "\n" ["    " <> templateBinding n <> "," | n <- names],
          "  )",
          "where",
          "",
          "import Data.Text (Text)",
          "import Graphics.Plotly.Internal.Embed (embedTemplate)",
          "import Graphics.Plotly.Types (Template)",
          "",
          "-- | Every template, under its plotly.py name.",
          "templates :: [(Text, Template)]",
          "templates ="
        ]
          <> leading "[ " ", " ["(" <> str n <> ", " <> templateBinding n <> ")" | n <- names]
          <> ["  ]"]
          <> concat
            [ [ "",
                "-- | " <> fromMaybe ("@" <> n <> "@, from plotly.py.") (lookup n templateDocs),
                templateBinding n <> " :: Template",
                templateBinding n <> " = $$(embedTemplate " <> str ("vendor/plotly.py/templates/" <> n <> ".json") <> ")"
              ]
            | n <- names
            ]

-- | The Haskell name of a template: @plotly_dark@ is @plotlyDark@.
templateBinding :: Text -> Text
templateBinding n = case T.splitOn "_" n of
  w : ws -> w <> T.concat (map pascal ws)
  [] -> n
