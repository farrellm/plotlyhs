{-# LANGUAGE OverloadedStrings #-}

-- | Renders plotly.py's colour scales, vendored as @colors.json@, as
-- @Graphics.Plotly.Colors.*@ modules.
module PlotlyGen.Colors
  ( renderColorModules,
    scaleName,
  )
where

import Control.Monad (forM, unless)
import Data.Aeson (Value (..))
import Data.Aeson.Key qualified as Key
import Data.Aeson.KeyMap qualified as KM
import Data.Char (isLower, isUpper, toLower)
import Data.Foldable (toList)
import Data.Text (Text)
import Data.Text qualified as T
import PlotlyGen.Naming (duplicates, pascal)
import PlotlyGen.Render (Module (..), leading, str)

-- | The modules of @colors.json@, in the order they are rendered, with
-- their documentation.
colorModules :: [(Text, Text)]
colorModules =
  [ ("qualitative", "Qualitative colour sequences, for data with no natural order, such as categories. They match @plotly.colors.qualitative@."),
    ("sequential", "Sequential colour scales, for most continuous data. They match @plotly.colors.sequential@."),
    ("diverging", "Diverging colour scales, for continuous data with a meaningful midpoint, such as zero. They match @plotly.colors.diverging@."),
    ("cyclical", "Cyclical colour scales, for data that wraps around, such as angles or times of day. They match @plotly.colors.cyclical@.")
  ]

-- | The modules, given plotly.py's version and the parsed @colors.json@.
renderColorModules :: Text -> Value -> Either String [Module]
renderColorModules version value = do
  o <- case value of
    Object o -> Right o
    _ -> Left "colors.json is not an object"
  let unknown = [Key.toText k | k <- KM.keys o, Key.toText k `notElem` map fst colorModules]
  unless (null unknown) $ Left ("colors.json has unknown modules: " <> show unknown)
  forM colorModules $ \(m, doc) -> do
    entries <- case KM.lookup (Key.fromText m) o of
      Just (Array a) -> traverse entry (toList a)
      _ -> Left ("colors.json has no " <> T.unpack m <> " list")
    let names = map (scaleName . fst) entries
        clashes = duplicates ("scales" : names)
    unless (null clashes) $ Left ("colour scale names clash in " <> T.unpack m <> ": " <> show clashes)
    pure (render m doc entries)
  where
    entry (Array a) | [String n, Array cs] <- toList a = (,) n <$> traverse color (toList cs)
    entry v = Left ("bad colour scale in colors.json: " <> show v)
    color (String c) = Right c
    color v = Left ("bad colour in colors.json: " <> show v)
    render m doc entries =
      Module ("Graphics.Plotly.Colors." <> pascal m) $
        T.unlines $
          [ "-- This module is generated by plotlyhs-gen from the colour scales of",
            "-- plotly.py " <> version <> ". Do not edit it; run plotlyhs-gen instead.",
            "{-# LANGUAGE OverloadedStrings #-}",
            "",
            "-- | " <> doc,
            "--",
            "-- Reverse a scale with 'reverse', and make a 'Graphics.Plotly.Types.Colorscale'",
            "-- of one with 'Graphics.Plotly.Colors.toColorscale'.",
            "module Graphics.Plotly.Colors." <> pascal m,
            "  ( scales,",
            T.intercalate "\n" ["    " <> scaleName n <> "," | (n, _) <- entries],
            "  )",
            "where",
            "",
            "import Data.Text (Text)",
            "import Graphics.Plotly.Types (Color)",
            "",
            "-- | Every scale in the module, under its plotly.py name.",
            "scales :: [(Text, [Color])]",
            "scales ="
          ]
            <> leading "[ " ", " ["(" <> str n <> ", " <> scaleName n <> ")" | (n, _) <- entries]
            <> ["  ]"]
            <> concat
              [ [ "",
                  "-- | @plotly.colors." <> m <> "." <> n <> "@.",
                  scaleName n <> " :: [Color]",
                  scaleName n <> " = [" <> T.intercalate ", " (map str cs) <> "]"
                ]
              | (n, cs) <- entries
              ]

-- | The Haskell name of a scale: its leading capitals in lower case, but for
-- the last of several when a lower-case letter follows. @Plotly@ is
-- @plotly@, @RdBu@ is @rdBu@, @PRGn@ is @prGn@ and @HSV@ is @hsv@.
scaleName :: Text -> Text
scaleName n = T.map toLower lowered <> rest
  where
    (caps, after) = T.span isUpper n
    (lowered, rest)
      | T.length caps > 1, Just (c, _) <- T.uncons after, isLower c = (T.init caps, T.cons (T.last caps) after)
      | otherwise = (caps, after)
